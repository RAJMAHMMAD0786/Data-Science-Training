# =========================
# COFFEE MACHINE
# =========================
class CoffeeMachine:
    def make_coffee(self, choice):
        menu = {
            1: Espresso(),
            2: Americano(),
            3: Latte(),
            4: Cappuccino(),
            5: Mocha()
        }

        coffee = menu.get(choice)

        if coffee:
            coffee.prepare()
        else:
            print("Invalid Choice")


